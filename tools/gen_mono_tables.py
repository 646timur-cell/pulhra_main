"""MONOFM's tables as a C header (eng_mono.c includes it in the MONOFM build only):

  DPRO_WAVE[32][129]  DIGIPRO's raw single cycles, 128 samples and the first again (for the interpolation), 12 bit
                      (multiples of 16 in an int16): the classic shapes, pulses, organ and vowel spectra, folded and
                      FM'd shapes, a stepped saw, a bit-crushed saw, a fixed noise, a logistic-map chaos
  DPRO_NAMES[32]      their names (five characters at most)

  gen_mono_tables.py OUT.h
Pure Python: the same bytes on every run.
"""
import math
import random
import sys
from pathlib import Path

TAU = 2 * math.pi
N = 128


def additive(parts):
    return [sum(a * math.sin(TAU * h * i / N + p) for h, a, p in parts) for i in range(N)]


def formant(f1, f2, f3, f0=110.0):
    """a voiced single cycle: the harmonics of f0 weighted by three formant peaks"""
    parts = []
    for h in range(1, 40):
        f = h * f0
        g = sum(a / (1 + ((f - fc) / bw) ** 2) for fc, bw, a in ((f1, 90, 1.0), (f2, 120, 0.6), (f3, 180, 0.35)))
        parts.append((h, g / h ** 0.3, 0.0))
    return additive(parts)


def waves():
    rnd = random.Random(808)
    W = []
    ph = [i / N for i in range(N)]
    W.append(("SINE", [math.sin(TAU * t) for t in ph]))
    W.append(("TRI", [1 - 4 * abs(t - 0.5) for t in ph]))
    W.append(("SAW", [2 * t - 1 for t in ph]))
    W.append(("SQR", [1 if t < 0.5 else -1 for t in ph]))
    W.append(("PL25", [1 if t < 0.25 else -1 for t in ph]))
    W.append(("PL12", [1 if t < 0.125 else -1 for t in ph]))
    W.append(("PL06", [1 if t < 0.0625 else -1 for t in ph]))
    W.append(("SIN8", [math.sin(TAU * t) + 0.5 * math.sin(2 * TAU * t) for t in ph]))
    W.append(("ORGAN", additive([(1, 1, 0), (2, 0.8, 0), (3, 0.6, 0), (4, 0.5, 0), (6, 0.35, 0), (8, 0.3, 0)])))
    W.append(("BRASS", additive([(h, 1 / h ** 0.7, 0) for h in range(1, 24)])))
    W.append(("STRNG", additive([(h, 1 / h, 0.3 * h) for h in range(1, 20)])))
    W.append(("VOX A", formant(730, 1090, 2440)))
    W.append(("VOX E", formant(530, 1840, 2480)))
    W.append(("VOX I", formant(270, 2290, 3010)))
    W.append(("VOX O", formant(570, 840, 2410)))
    W.append(("VOX U", formant(300, 870, 2240)))
    W.append(("ODD", additive([(h, 1 / h, 0) for h in (1, 3, 5, 7, 9, 11)])))
    W.append(("SINC", [math.sin(TAU * 6 * (t - 0.5)) / (TAU * 6 * (t - 0.5)) if t != 0.5 else 1.0 for t in ph]))
    W.append(("HALF", [max(0.0, math.sin(TAU * t)) * 2 - 0.64 for t in ph]))
    W.append(("RECT", [abs(math.sin(TAU * t)) * 2 - 1.27 for t in ph]))
    W.append(("SIN3", [math.sin(TAU * t) ** 3 for t in ph]))
    W.append(("STAIR", [math.floor(t * 5) / 2.0 - 1 for t in ph]))
    W.append(("BITS", [math.floor((2 * t - 1) * 4) / 4 for t in ph]))
    W.append(("FM 1", [math.sin(TAU * t + 1.5 * math.sin(TAU * t)) for t in ph]))
    W.append(("FM 2", [math.sin(TAU * t + 3.0 * math.sin(2 * TAU * t)) for t in ph]))
    W.append(("FM 5", [math.sin(TAU * t + 2.0 * math.sin(5 * TAU * t)) for t in ph]))
    W.append(("NOISE", [rnd.uniform(-1, 1) for _ in ph]))
    W.append(("SYNC", [2 * ((t * 2.5) % 1.0) - 1 for t in ph]))
    W.append(("SAWSQ", [(2 * t - 1) + (1 if t < 0.5 else -1) for t in ph]))
    W.append(("PWM2", [(1 if t < 0.3 else -1) + (1 if (t + 0.4) % 1.0 < 0.2 else -1) for t in ph]))
    W.append(("RESO", [math.sin(TAU * 7 * t) * (1 - t) for t in ph]))
    x, ch = 0.37, []
    for _ in ph:
        x = 3.91 * x * (1 - x)
        ch.append(2 * x - 1)
    W.append(("CHAOS", ch))
    assert len(W) == 32
    out = []
    for name, w in W:
        mean = sum(w) / N
        w = [v - mean for v in w]
        m = max(1e-9, max(abs(v) for v in w))
        q = [max(-2047, min(2047, round(v / m * 2047))) * 16 for v in w]
        out.append((name, q + q[:1]))
    return out


def main(out):
    W = waves()
    L = ["/* generated by tools/gen_mono_tables.py: MONOFM's DIGIPRO single cycles (12 bit, 128 samples + 1) */",
         "#pragma once", f"#define DPRO_N {len(W)}", "#define DPRO_LEN 128",
         "static const int16_t DPRO_WAVE[DPRO_N][DPRO_LEN + 1] = {"]
    for name, q in W:
        L.append(f"    {{ /* {name} */")
        for i in range(0, len(q), 16):
            L.append("        " + ", ".join(str(v) for v in q[i:i + 16]) + ",")
        L.append("    },")
    L.append("};")
    L.append("static const char *const DPRO_NAMES[DPRO_N] = {" + ", ".join(f'"{n}"' for n, _ in W) + "};")
    L.append("")
    Path(out).write_text("\n".join(L))
    print(f"mono tables: {len(W)} DIGIPRO waves")


if __name__ == "__main__":
    main(sys.argv[1])
